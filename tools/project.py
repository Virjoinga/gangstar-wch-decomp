"""Shared helpers: repository paths, the base library and table IO."""

from __future__ import annotations

import csv
import os
from pathlib import Path

from .elf import ElfFile

#: The repository root, derived from the location of this file.
ROOT = Path(__file__).resolve().parent.parent

#: Where the retail shared object lives inside a checkout.  It is git ignored:
#: game data is never committed to this repository.
BASE_LIB_DIR = ROOT / "baselib"
BASE_LIB_NAME = "libsanangeles.so"

#: The SHA-256 of the retail library this repository was built against.  The
#: symbol map and the function catalogue are only valid for this exact file.
BASE_LIB_SHA256 = "b322b642d365a34c48e140234b7ef4efd965d1e81acd2b95d9034e2f4386ea8a"

#: Where the retail library was originally found on the author's machine.
KNOWN_LOCATIONS = (
    Path(r"C:\Users\GAMING\Downloads\libsanangeles.so"),
    BASE_LIB_DIR / BASE_LIB_NAME,
)


def repo_path(*parts: str) -> Path:
    """A path inside the repository."""
    return ROOT.joinpath(*parts)


def find_base_library(explicit: str | os.PathLike[str] | None = None) -> Path:
    """Locate the retail shared object.

    The search order is: an explicit path, the ``WCH_BASE_LIB`` environment
    variable, the git ignored ``baselib/`` directory, then the well known
    locations the library was originally distributed from.
    """
    if explicit:
        path = Path(explicit)
        if not path.is_file():
            raise FileNotFoundError(f"base library not found: {path}")
        return path

    env = os.environ.get("WCH_BASE_LIB")
    if env:
        path = Path(env)
        if path.is_file():
            return path

    for candidate in KNOWN_LOCATIONS:
        if candidate.is_file():
            return candidate

    raise FileNotFoundError(
        "the retail library 'libsanangeles.so' was not found.\n"
        "Place it in baselib/ or point WCH_BASE_LIB at it:\n"
        "  set WCH_BASE_LIB=/path/to/libsanangeles.so"
    )


def load_base_library(explicit: str | os.PathLike[str] | None = None) -> tuple[ElfFile, Path]:
    """Load and return the retail library together with the path it came from."""
    path = find_base_library(explicit)
    return ElfFile.load(str(path)), path


def write_tsv(path: Path, header: list[str], rows: list[list[object]]) -> None:
    """Write a tab separated table with a generated-file banner."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(
            "# %s\n"
            "# Generated by tools/%s -- DO NOT EDIT BY HAND.\n"
            "# Run `python tools/%s` to regenerate.\n"
            % (path.name, path.name.replace(".tsv", ".py"), path.name.replace(".tsv", ".py"))
        )
        writer = csv.writer(handle, delimiter="\t", lineterminator="\n")
        writer.writerow(header)
        for row in rows:
            writer.writerow(row)


def read_tsv(path: Path) -> list[dict[str, str]]:
    """Read a table written by :func:`write_tsv`."""
    if not path.exists():
        return []
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(
            (line for line in handle if not line.startswith("#")), delimiter="\t"
        )
        return list(reader)
